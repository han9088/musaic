  static void registerWith() {
    MusicKitPlatform.instance = AppleMusicKitWebPlatform();
  }

  static const _cdn = 'https://js-cdn.music.apple.com/musickit/v3/musickit.js';

  static Future<MusicKitGlobal?>? _loadFuture;
  static MusicKitInstance? _instance;

  bool _disposed = false;
  final _listeners = <String, JSFunction>{};
  StreamController<MusicAuthorizationStatus>? _authEvents;
  StreamController<MusicPlayerState>? _stateEvents;
  MusicPlayerState _lastState = const MusicPlayerState.initial();
  List<MusicItemRef> _queue = [];

  /// Loads the MusicKit JS script (once per page) and configures it.
  Future<MusicKitInstance> _ensureInstance(
      MusicKitPlatformConfig config) async {
    if (_disposed) {
      throw MusicKitException(MusicKitErrorCode.alreadyDisposed,
          message: 'Web platform disposed.');
    }
    if (_instance != null) return _instance!;
    final loadFuture = _loadFuture ??= _loadScript();
    final global = await loadFuture;
    if (global == null) {
      // Do not cache a failed load; the next call retries.
      if (identical(_loadFuture, loadFuture)) _loadFuture = null;
      throw MusicKitException(
        MusicKitErrorCode.sdkUnavailable,
        message: 'Failed to load MusicKit JS from $_cdn. Check your '
            'network, CSP settings, and browser console.',
        platform: 'web',
      );
    }

    final token = await _developerToken(config);
    if (token == null) {
      throw MusicKitException(
        MusicKitErrorCode.developerTokenMissing,
        message: 'AppleMusicConfig.developerTokenProvider is required on '
            'Web. It must return a developer token generated by your server.',
        platform: 'web',
      );
    }

    final configured = await global
        .configure(
          MusicKitConfiguration(
            developerToken: token,
            app: MusicKitAppConfiguration(
              name: config.appName ?? 'Flutter App',
              build: config.appBuild ?? '1.0.0',
            ),
          ),
        )
        .toDart;

    _instance = configured;
    _attachListeners(configured);
    return configured;
  }

  Future<String?> _developerToken(MusicKitPlatformConfig config) async {
    final provider = config.developerTokenProvider;
    if (provider == null) return null;
    try {
      return await provider.getToken();
    } catch (e) {
      throw MusicKitException(
        MusicKitErrorCode.developerTokenMissing,
        message: 'developerTokenProvider failed: $e',
        platform: 'web',
      );
    }
  }

  static Future<MusicKitGlobal?> _loadScript() async {
    final existing = _musicKitGlobalIfReady();
    if (existing != null) return existing;
    final completer = Completer<MusicKitGlobal?>();
    final document = window.document;
    final script = document.createElement('script') as HTMLScriptElement;
    script.src = _cdn;
    script.async = true;
    final handler = ((JSAny? _) {
      if (!completer.isCompleted) completer.complete(_musicKitGlobalIfReady());
    }).toJS;
    script.onerror = ((JSAny? _) {
      if (!completer.isCompleted) completer.complete(null);
    }).toJS;
    document.addEventListener('musickitloaded', handler);
    final timer = Timer(const Duration(seconds: 20), () {
      if (!completer.isCompleted) completer.complete(null);
    });
    document.head!.appendChild(script);
    try {
      final loaded = await completer.future;
      if (loaded == null) script.remove();
      return loaded;
    } finally {
      timer.cancel();
      document.removeEventListener('musickitloaded', handler);
      script.onerror = null;
    }
  }

  /// Reflective property getter via the shared `Reflect.get` binding
  /// declared at the bottom of this file (and in musickit_js.dart).
  static JSAny? _reflectGet(JSObject obj, String key) =>
      jsReflectGet(obj, key.toJS);

  /// Returns the MusicKit global when the SDK is loaded and configured,
  /// else null.
  static MusicKitGlobal? _musicKitGlobalIfReady() {
    final existing = _reflectGet(window, 'MusicKit');
    if (existing == null || existing == false.toJS || existing == 0.toJS) {
      return null;
    }
    return existing.isA<JSObject>() ? existing as MusicKitGlobal : null;
  }

  void _listen(MusicKitInstance instance, JSString name, JSFunction callback) {
    _listeners[name.toDart] = callback;
    instance.addEventListener(name, callback);
  }

  void _attachListeners(MusicKitInstance instance) {
    _authEvents ??= StreamController<MusicAuthorizationStatus>.broadcast();
    _stateEvents ??= StreamController<MusicPlayerState>.broadcast();

    _listen(
        instance,
        'authorizationStatusDidChange'.toJS,
        ((JSAny? e) {
          final status = instance.authorizationStatusValue;
          _authEvents?.add(_authStatusFromJs(status));
          return null;
        }).toJS);

    const eventNames = [
      'playbackStateDidChange',
      'playbackTimeDidChange',
      'nowPlayingItemDidChange',
      'queueItemsDidChange',
    ];
    for (final name in eventNames) {
      _listen(
          instance,
          name.toJS,
          ((JSAny? e) {
            final state = _stateFromInstance(instance);
            _lastState = state;
            _stateEvents?.add(state);
            return null;
          }).toJS);
    }
  }

  MusicAuthorizationStatus _authStatusFromJs(int status) => switch (status) {
        3 => MusicAuthorizationStatus.authorized,
        2 => MusicAuthorizationStatus.denied,
        1 => MusicAuthorizationStatus.restricted,
        _ => MusicAuthorizationStatus.notDetermined,
      };

  MusicPlayerState _stateFromInstance(MusicKitInstance instance) {
    final playbackState = instance.playbackStateValue;
    final status = switch (playbackState) {
      1 => MusicPlayerStatus.loading,
      2 => MusicPlayerStatus.playing,
      3 => MusicPlayerStatus.paused,
      4 => MusicPlayerStatus.stopped,
      5 || 10 => MusicPlayerStatus.completed,
      6 || 7 || 8 || 9 => MusicPlayerStatus.buffering,
      _ => MusicPlayerStatus.idle,
    };
    final item = instance.currentPlayerItem;
    final attrs = item?.attributes;
    final attrMap = attrs == null ? null : jsDartify(attrs) as Map?;
    return MusicPlayerState(
      status: status,
      currentItem: item == null
          ? null
          : MusicItemRef(
              id: item.idValue,
              type: MusicResourceType.fromWireName(item.typeValue) ??
                  MusicResourceType.song,
              source: item.typeValue.startsWith('library-')
                  ? MusicItemSource.library
                  : MusicItemSource.catalog,
            ),
      currentIndex: instance.currentPlayerItemIndexValue,
      position: Duration(
          milliseconds: (instance.currentPlaybackTimeValue * 1000).round()),
      duration: attrMap == null
          ? null
          : attrMap['durationInMillis'] is num
              ? Duration(
                  milliseconds: (attrMap['durationInMillis'] as num).toInt())
              : null,
      queueLength: _queue.length,
      shuffleMode: instance.shuffleEnabledValue
          ? MusicShuffleMode.on
          : MusicShuffleMode.off,
      repeatMode: switch (instance.repeatModeValue) {
        1 => MusicRepeatMode.one,
        2 => MusicRepeatMode.all,
        _ => MusicRepeatMode.off,
      },
      isPlaying: playbackState == 2,
      isBuffering: playbackState == 6 || playbackState == 8,
    );
  }

