  @override
  Future<void> initialize(MusicKitPlatformConfig config) async {
    _disposed = false;
    await _ensureInstance(config);
  }

  @override
  Future<void> dispose({bool stopPlayback = false}) async {
    if (_disposed) return;
    _disposed = true;
    if (stopPlayback && _instance != null) {
      try {
        await _instance!.stop().toDart;
      } catch (_) {
        // Stopping a disposed/failed player is best-effort.
      }
    }
    final instance = _instance;
    if (instance != null) {
      for (final entry in _listeners.entries) {
        instance.removeEventListener(entry.key.toJS, entry.value);
      }
    }
    _listeners.clear();
    _queue = [];
    _lastState = const MusicPlayerState.initial();
    // Release the singleton so a new client can re-initialize.
    _instance = null;
    if (_authEvents != null) unawaited(_authEvents!.close());
    _authEvents = null;
    if (_stateEvents != null) unawaited(_stateEvents!.close());
    _stateEvents = null;
  }

  MusicKitInstance get _requireInstance {
    final i = _instance;
    if (i == null) {
      throw MusicKitException(
        MusicKitErrorCode.notInitialized,
        message: 'Web platform: call initialize() first.',
        platform: 'web',
      );
    }
    return i;
  }

  @override
  Future<MusicAuthorizationStatus> getAuthorizationStatus() async =>
      _authStatusFromJs(_requireInstance.authorizationStatusValue);

  @override
  Future<MusicAuthorizationStatus> requestAuthorization() async {
    final instance = _requireInstance;
    try {
      // Must be triggered by a user gesture (button tap); calling this
      // from build() will be blocked by the browser's popup blocker.
      await instance.authorize().toDart;
    } catch (e) {
      throw MusicKitException(
        MusicKitErrorCode.authorizationCancelled,
        message: 'Authorization failed or was cancelled: $e',
        platform: 'web',
      );
    }
    return _authStatusFromJs(instance.authorizationStatusValue);
  }

  @override
  Stream<MusicAuthorizationStatus> get onAuthorizationChanged {
    final controller = _authEvents;
    if (controller == null) {
      return Stream.value(MusicAuthorizationStatus.notDetermined);
    }
    return controller.stream;
  }

  @override
  Future<MusicSubscription> getSubscription() async {
    final instance = _requireInstance;
    final hasSubscription =
        (await instance.hasMusicSubscription().toDart).toDart;
    return MusicSubscription(
      status: hasSubscription
          ? MusicSubscriptionStatus.subscribed
          : MusicSubscriptionStatus.notSubscribed,
      canPlayCatalogContent: hasSubscription,
    );
  }

  @override
  Future<MusicCapabilities> getCapabilities() async {
    final authorized = await getAuthorizationStatus();
    const supported = MusicCapability.supported();
    return MusicCapabilities(
      canPlayCatalog: supported,
      canAccessLibrary: MusicCapability(
        supported: authorized == MusicAuthorizationStatus.authorized,
        reason: authorized == MusicAuthorizationStatus.authorized
            ? MusicCapabilityReason.available
            : MusicCapabilityReason.authorizationRequired,
      ),
      canSeek: supported,
      canSetQueue: supported,
      canEditQueue: const MusicCapability.unsupported(
        MusicCapabilityReason.unsupportedOnPlatform,
        detail: 'Appending is supported; removing queue entries is not.',
      ),
      canShuffle: supported,
      canRepeat: supported,
      // The plugin exposes no volume API; report honestly.
      canControlVolume: const MusicCapability.unsupported(
        MusicCapabilityReason.unsupportedOnPlatform,
        detail: 'Volume is controlled by the browser/OS on Web.',
      ),
      canPlayInBackground: const MusicCapability.unsupported(
        MusicCapabilityReason.unsupportedOnPlatform,
        detail: 'Browsers suspend audio in background tabs.',
      ),
      canCreatePlaylist: MusicCapability(
        supported: authorized == MusicAuthorizationStatus.authorized,
        reason: authorized == MusicAuthorizationStatus.authorized
            ? MusicCapabilityReason.available
            : MusicCapabilityReason.authorizationRequired,
      ),
    );
  }

