  @override
  Future<MusicCreatedPlaylist> createPlaylist(String name,
      {String? description, List<MusicItemRef>? tracks}) async {
    final instance = _requireInstance;
    try {
      final body = <String, Object?>{
        if (tracks != null)
          'relationships': {
            'tracks': {
              'data': tracks
                  .map((t) => {
                        'id': t.id,
                        'type': t.source == MusicItemSource.library
                            ? 'library-${t.type.wireName}'
                            : t.type.wireName
                      })
                  .toList()
            }
          },
        'attributes': {
          'name': name,
          if (description != null) 'description': description,
        },
      };
      final response = await instance
          .api('POST'.toJS, 'v1/me/library/playlists'.toJS, null, body.jsify()!)
          .toDart;
      final envelope = jsDartify(response);
      final dart = envelope is Map ? envelope['data'] : null;
      final data = (dart is Map && dart['data'] is List)
          ? dart['data'] as List
          : const <dynamic>[];
      final created = data.isEmpty
          ? const <String, dynamic>{}
          : Map<String, dynamic>.from(data.first as Map);
      final attrs = created['attributes'] as Map<String, dynamic>?;
      return MusicCreatedPlaylist(
        id: created['id'] as String? ?? '',
        name: attrs?['name'] as String? ?? name,
        description: (attrs?['description'] as Map?)?['standard'] as String?,
      );
    } on MusicKitException {
      rethrow;
    } catch (e) {
      throw MusicKitException(
        MusicKitErrorCode.resourceUnavailable,
        message: 'Failed to create playlist: $e',
        platform: 'web',
      );
    }
  }

  @override
  Future<MusicAddToPlaylistResult> addToPlaylist(
      String playlistLibraryId, List<MusicItemRef> tracks) async {
    if (tracks.isEmpty) {
      return MusicAddToPlaylistResult(
          playlistId: playlistLibraryId, addedRefs: tracks);
    }
    try {
      final body = <String, Object?>{
        'data': tracks
            .map((t) => {
                  'id': t.id,
                  'type': t.source == MusicItemSource.library
                      ? 'library-${t.type.wireName}'
                      : t.type.wireName
                })
            .toList(),
      };
      await _requireInstance
          .api(
            'POST'.toJS,
            'v1/me/library/playlists/${_pathSegment(playlistLibraryId, what: 'playlist id')}/tracks'
                .toJS,
            null,
            body.jsify()!,
          )
          .toDart;
      return MusicAddToPlaylistResult(
          playlistId: playlistLibraryId, addedRefs: tracks);
    } on MusicKitException {
      rethrow;
    } catch (e) {
      throw MusicKitException(
        MusicKitErrorCode.resourceUnavailable,
        message: 'Failed to add tracks to playlist: $e',
        platform: 'web',
      );
    }
  }

  Future<MusicKitQueueOptions> _queueOptions(List<MusicItemRef> items) async {
    final resolved = <MusicKitQueueItem>[];
    for (final item in items) {
      if (item.type != MusicResourceType.song) {
        throw const MusicKitException(MusicKitErrorCode.unsupportedFeature,
            message:
                'Queue entries must be songs. Expand albums or playlists first.');
      }
      final path = item.source == MusicItemSource.library
          ? 'v1/me/library/songs/${_pathSegment(item.id)}'
          : 'v1/catalog/${await _storefront(item.storefront)}/songs/${_pathSegment(item.id)}';
      final json = await _apiGet(_requireInstance, path);
      final data = json['data'] as List?;
      if (data == null || data.isEmpty) {
        throw const MusicKitException(MusicKitErrorCode.resourceNotFound,
            message: 'Queue item not found.');
      }
      resolved.add((data.first as Map).jsify() as MusicKitQueueItem);
    }
    return MusicKitQueueOptions(items: resolved.toJS);
  }

  // ---------------- player ----------------

  @override
  Future<void> setQueue(List<MusicItemRef> items,
      {int startIndex = 0, bool autoplay = true}) async {
    final instance = _requireInstance;
    if (items.isEmpty || startIndex < 0 || startIndex >= items.length) {
      throw const MusicKitException(MusicKitErrorCode.resourceUnavailable,
          message: 'Queue must be nonempty with a valid start index.');
    }
    try {
      await instance.setQueue(await _queueOptions(items)).toDart;
      _queue = List.of(items);
      instance.queue.position = startIndex;
      if (autoplay) await instance.play().toDart;
    } catch (e) {
      throw MusicKitException(
        MusicKitErrorCode.playbackFailed,
        message: 'Failed to set queue: $e',
        platform: 'web',
      );
    }
  }

  @override
  Future<void> play() async {
    try {
      await _requireInstance.play().toDart;
    } catch (e) {
      throw MusicKitException(MusicKitErrorCode.playbackFailed,
          message: 'play() failed: $e', platform: 'web');
    }
  }

  @override
  Future<void> pause() async => _requireInstance.pause().toDart;

  @override
  Future<void> stop() async => _requireInstance.stop().toDart;

  @override
  Future<void> togglePlayPause() async {
    if (_requireInstance.playbackStateValue == 2) {
      await pause();
    } else {
      await play();
    }
  }

  @override
  Future<void> seekTo(Duration position) async =>
      _requireInstance.seekToTime((position.inMilliseconds / 1000).toJS).toDart;

  @override
  Future<void> skipToNext() async {
    try {
      await _requireInstance.skipToNext().toDart;
    } catch (_) {
      // At queue end MusicKit JS rejects the promise; treat as end-of-queue.
    }
  }

  @override
  Future<void> skipToPrevious() async {
    try {
      await _requireInstance.skipToPrevious().toDart;
    } catch (_) {
      // At queue start MusicKit JS rejects the promise; ignore.
    }
  }

  @override
  Future<MusicQueue> getQueue() async {
    final instance = _requireInstance;
    return MusicQueue(
      entries:
          _queue.map((r) => MusicQueueEntry(ref: r)).toList(growable: false),
      currentIndex: instance.currentPlayerItemIndexValue,
    );
  }

  @override
  Future<void> appendToQueue(List<MusicItemRef> items) async {
    final instance = _requireInstance;
    try {
      await instance.queueAppend(await _queueOptions(items)).toDart;
      _queue.addAll(items);
    } catch (e) {
      throw MusicKitException(
        MusicKitErrorCode.unsupportedFeature,
        message: 'Queue append failed: $e',
        platform: 'web',
      );
    }
  }

  @override
  Future<void> removeFromQueue(int index) async {
    throw const MusicKitException(MusicKitErrorCode.unsupportedFeature,
        message: 'MusicKit JS exposes no public queue removal API.',
        platform: 'web');
  }

  @override
  Future<void> setShuffleMode(MusicShuffleMode mode) async {
    _requireInstance.shuffleMode = mode == MusicShuffleMode.on ? 1 : 0;
  }

  @override
  Future<void> setRepeatMode(MusicRepeatMode mode) async {
    _requireInstance.repeatModeValue = switch (mode) {
      MusicRepeatMode.off => 0,
      MusicRepeatMode.one => 1,
      MusicRepeatMode.all => 2,
    };
  }

  @override
  Stream<MusicPlayerState> get playerStates => Stream.multi((controller) {
        final events = _stateEvents;
        if (events == null || events.isClosed) {
          controller.addSync(_lastState);
          controller.closeSync();
          return;
        }
        final subscription = events.stream.listen(controller.addSync,
            onError: controller.addErrorSync, onDone: controller.closeSync);
        controller.addSync(_lastState);
        controller.onCancel = subscription.cancel;
      }, isBroadcast: true);
}
