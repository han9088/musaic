  Future<String> _storefront(String? explicit) async {
    if (explicit != null) return explicit;
    final instance = _requireInstance;
    final json = await _apiGet(instance, 'v1/me/storefront');
    final data = (json['data'] as List<dynamic>?);
    if (data != null && data.isNotEmpty) {
      return (data.first as Map<String, dynamic>)['id'] as String? ?? 'us';
    }
    return 'us';
  }

  Future<Map<String, dynamic>> _apiGet(
      MusicKitInstance instance, String path) async {
    final JSAny? response;
    try {
      response = await instance.api('GET'.toJS, path.toJS).toDart;
    } on MusicKitException {
      rethrow;
    } catch (e) {
      throw _apiError(e, 'GET $path');
    }
    try {
      final envelope = jsDartify(response);
      final data = envelope is Map ? envelope['data'] : null;
      if (data is Map<String, dynamic>) return data;
      if (data is Map) return Map<String, dynamic>.from(data);
    } catch (_) {
      // Decoding is separate from transport: malformed data is not a network error.
    }
    throw const MusicKitException(MusicKitErrorCode.unknown,
        message: 'Malformed Apple Music API response.',
        platform: 'web',
        details: {'reason': 'invalidResponse'});
  }

  /// Maps a failed MusicKit JS API call to a [MusicKitException] with the
  /// most specific error code available.
  MusicKitException _apiError(Object e, String context) {
    // MusicKit JS rejects with a Response-like object carrying `status`
    // (and sometimes `statusText` / `body`).
    int? status;
    try {
      final obj = (e as JSAny?)?.isA<JSObject>() == true ? e as JSObject : null;
      if (obj != null) {
        final s = _reflectGet(obj, 'status');
        if (s != null && s.isA<JSNumber>()) {
          status = (s as JSNumber).toDartInt;
        }
      }
    } catch (_) {
      // Not a Response-like rejection; fall through.
    }
    final code = switch (status) {
      401 => MusicKitErrorCode.authenticationFailed,
      403 => MusicKitErrorCode.authorizationDenied,
      404 => MusicKitErrorCode.resourceNotFound,
      409 || 410 => MusicKitErrorCode.resourceUnavailable,
      429 => MusicKitErrorCode.rateLimited,
      408 => MusicKitErrorCode.requestTimeout,
      int code when code >= 500 && code <= 599 =>
        MusicKitErrorCode.networkError,
      null => MusicKitErrorCode.networkError,
      _ => MusicKitErrorCode.unknown,
    };
    return MusicKitException(
      code,
      message: 'Apple Music API request failed ($context'
          '${status == null ? '' : ', HTTP $status'}).',
      platform: 'web',
      details: status == null ? null : {'status': status},
    );
  }

  /// Encodes [segment] for safe interpolation into an API path.
  ///
  /// Rejects empty segments and characters that could alter the path
  /// (`/`, `?`, `#`, `&`), mapping violations to resourceNotFound rather
  /// than letting a malformed id change which endpoint is called.
  String _pathSegment(String segment, {String what = 'id'}) {
    if (segment.isEmpty ||
        segment.contains('/') ||
        segment.contains('?') ||
        segment.contains('#') ||
        segment.contains('&')) {
      throw MusicKitException(
        MusicKitErrorCode.resourceNotFound,
        message: 'Invalid $what: $segment',
        platform: 'web',
      );
    }
    return Uri.encodeComponent(segment);
  }

  MusicPage<T>? _pageFromJson<T>(
      Object? json, T Function(Map<String, dynamic>) convert) {
    if (json == null || json is! Map) return null;
    return MusicPage.fromApiJson(Map<String, dynamic>.from(json), convert);
  }

  @override
  Future<MusicSearchResult> searchCatalog(
    String term, {
    Set<MusicResourceType> types = const {
      MusicResourceType.song,
      MusicResourceType.album,
      MusicResourceType.artist,
      MusicResourceType.playlist
    },
    int limit = 25,
    String? storefront,
  }) async {
    final instance = _requireInstance;
    final query = 'term=${Uri.encodeComponent(term)}&limit=$limit'
        '&types=${types.map((t) => t.wireName).join(',')}';
    final json = await _apiGet(
        instance, 'v1/catalog/${await _storefront(storefront)}/search?$query');
    final results = (json['results'] as Map<String, dynamic>?) ?? const {};
    return MusicSearchResult(
      songs: _pageFromJson(results['songs'], MusicSong.fromApiJson),
      albums: _pageFromJson(results['albums'], MusicAlbum.fromApiJson),
      artists: _pageFromJson(results['artists'], MusicArtist.fromApiJson),
      playlists: _pageFromJson(results['playlists'], MusicPlaylist.fromApiJson),
    );
  }

