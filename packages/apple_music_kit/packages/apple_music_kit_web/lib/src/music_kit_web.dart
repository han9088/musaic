  @override
  Future<List<MusicChart>> getCharts(MusicChartKind kind,
      {String? storefront, int limit = 20}) async {
    final instance = _requireInstance;
    // The Apple Music API returns charts grouped under kebab-case keys
    // ("songs", "albums", "music-videos").
    final wireKind = switch (kind) {
      MusicChartKind.songs => 'songs',
      MusicChartKind.albums => 'albums',
      MusicChartKind.musicVideos => 'music-videos',
    };
    final json = await _apiGet(instance,
        'v1/catalog/${await _storefront(storefront)}/charts?types=$wireKind&limit=$limit');
    final results = (json['results'] as Map<String, dynamic>?) ?? const {};
    final chartsJson = (results[wireKind] as List<dynamic>?) ?? const [];
    return chartsJson.map((c) {
      final m = Map<String, dynamic>.from(c as Map);
      return MusicChart(
        kind: kind,
        name: m['name'] as String? ?? '',
        // Only populate the page matching the requested kind; never mix
        // songs into albums or vice versa.
        songs: kind == MusicChartKind.songs
            ? _pageFromJson({'data': m['data']}, MusicSong.fromApiJson)
            : null,
        albums: kind == MusicChartKind.albums
            ? _pageFromJson({'data': m['data']}, MusicAlbum.fromApiJson)
            : null,
      );
    }).toList(growable: false);
  }

