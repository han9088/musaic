import 'package:apple_music_kit_platform_interface/apple_music_kit_platform_interface.dart';

final class AppleMusicKitAndroid extends MethodChannelMusicKit {
  AppleMusicKitAndroid() : super('android');
  static void registerWith() =>
      MusicKitPlatform.instance = AppleMusicKitAndroid();
  @override
  Future<void> initialize(MusicKitPlatformConfig config) async {
    final provider = config.developerTokenProvider;
    String? token;
    if (provider != null) {
      try {
        token = await provider.getToken();
      } catch (e) {
        throw MusicKitException(
          MusicKitErrorCode.developerTokenMissing,
          message: 'developerTokenProvider failed: $e',
          platform: 'android',
        );
      }
    }
    if (token == null || token.isEmpty) {
      // Fail fast per the documented contract: Android requires a
      // developer token.
      throw MusicKitException(
        MusicKitErrorCode.developerTokenMissing,
        message: 'AppleMusicConfig.developerTokenProvider is required on '
            'Android. It must return a developer token generated by your '
            'server.',
        platform: 'android',
      );
    }
    await invoke<void>('initialize', {'developerToken': token});
  }
}
